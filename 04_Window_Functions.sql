select
	Order_ID,
	Order_Value_INR,
	CASE
		WHEN ORDER_VALUE_INR <350 THEN 'LOW'
		WHEN ORDER_VALUE_INR BETWEEN 350 AND 1500 THEN 'MEDIUM'
		WHEN ORDER_VALUE_INR >1500 THEN 'HIGH'
		ELSE 'UNKNOWN'
	END AS SEGMENT
from Ecommerce_Delivery_Analytics_New


---------------------------------------------------------

WITH SEGMENT_STATE AS(
select
	Order_ID,
	Order_Value_INR,
	CASE
		WHEN ORDER_VALUE_INR <500 THEN 'LOW'
		WHEN ORDER_VALUE_INR BETWEEN 500 AND 1000 THEN 'MEDIUM'
		WHEN ORDER_VALUE_INR >1000 THEN 'HIGH'
		ELSE 'UNKNOWN'
	END AS SEGMENT
FROM Ecommerce_Delivery_Analytics_New
)

SELECT 
	SEGMENT,
	COUNT(Order_ID) AS [NUMBER OF ORDERS],
	SUM(Order_Value_INR) AS [REVENUE],
	AVG(Order_Value_INR)[AVG ORDERS],
	ROUND(COUNT(Order_ID)*100.0/SUM(COUNT(ORDER_ID)) OVER(),2) AS [% ORDER]
FROM SEGMENT_STATE
GROUP BY SEGMENT
ORDER BY [% ORDER] ASC;


